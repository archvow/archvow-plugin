package org.archvow.vow.core;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Random;
import java.util.stream.Stream;

/**
 * Writes what this .vow reader gives - tokens, problems, header, links - on the shared sample vows and
 * on vows broken on purpose, to {@code contract/vow-reader/expected.json}. The VS Code extension's reader
 * (TypeScript) is tested against that file: both readers must give the same. {@code ./gradlew
 * contractDump} after a change of the reader, then run the extension's tests.
 *
 * <p>Arguments: the folder of sample vows, the output file.
 */
public final class DumpContract {
    /** The broken vows: a fixed seed, so the file changes only when the reader does. */
    private static final long SEED = 20261025L;
    private static final int BROKEN = 400;

    private DumpContract() {
    }

    public static void main(String[] args) throws IOException {
        Path samples = Path.of(args.length > 0 ? args[0] : "../contract/vows");
        Path out = Path.of(args.length > 1 ? args[1] : "../contract/vow-reader/expected.json");
        List<Path> files = new ArrayList<>();
        try (Stream<Path> walk = Files.walk(samples)) {
            walk.filter(p -> p.toString().endsWith(".vow")).sorted().forEach(files::add);
        }
        StringBuilder json = new StringBuilder("{\n\"comment\": ");
        string(json, "Generated by DumpContract (IntelliJ plugin, Java): what the .vow reader gives. "
                + "Samples are read from contract/vows/<file>; broken cases carry their text. "
                + "Tokens: [kind, start, end, state]; problems: [line, start, end, message, warning]; "
                + "links: [kind, target, start, end].");
        json.append(",\n\"cases\": [\n");
        List<String> texts = new ArrayList<>();
        boolean first = true;
        for (Path file : files) {
            String text = Files.readString(file, StandardCharsets.UTF_8);
            texts.add(text);
            first = writeCase(json, first, samples.relativize(file).toString().replace('\\', '/'), null, text);
        }
        Random random = new Random(SEED);
        for (int n = 0; n < BROKEN; n++) {
            String text = broken(random, texts.get(random.nextInt(texts.size())));
            first = writeCase(json, first, "broken-" + n, text, text);
        }
        json.append("\n]\n}\n");
        Files.createDirectories(out.getParent());
        Files.writeString(out, json.toString(), StandardCharsets.UTF_8);
        System.out.println("contract: " + files.size() + " sample vows and " + BROKEN + " broken ones -> " + out);
    }

    /** A few lines of a sample, damaged the ways people damage vows. */
    static String broken(Random random, String sample) {
        String[] lines = sample.split("\n", -1);
        int from = random.nextInt(lines.length);
        int count = 1 + random.nextInt(12);
        List<String> part = new ArrayList<>();
        if (random.nextInt(3) > 0) {
            part.add(lines[0]);  // most keep the first line
        }
        for (int i = from; i < Math.min(lines.length, from + count); i++) {
            part.add(lines[i]);
        }
        int damages = 1 + random.nextInt(3);
        for (int d = 0; d < damages && !part.isEmpty(); d++) {
            int at = random.nextInt(part.size());
            String line = part.get(at);
            int pos = line.isEmpty() ? 0 : random.nextInt(line.length() + 1);
            String damaged = switch (random.nextInt(14)) {
                case 0 -> "\t" + line;
                case 1 -> " " + line;
                case 2 -> "   " + line;
                case 3 -> line.substring(0, pos) + "\"" + line.substring(pos);
                case 4 -> line.substring(0, pos) + "," + line.substring(pos);
                case 5 -> line.substring(0, pos) + "[" + line.substring(pos);
                case 6 -> line.substring(0, pos) + "]" + line.substring(pos);
                case 7 -> line.isEmpty() ? line : line.substring(0, pos) + line.substring(Math.min(line.length(), pos + 1));
                case 8 -> line + " = {\"a\": [1, 2.5e3, \"x\\\"y\"], \"b\": null}";
                case 9 -> line + " = {\"a\": [1,}";
                case 10 -> line + "\r";
                case 11 -> line.substring(0, pos) + "{}" + line.substring(pos);
                case 12 -> line.substring(0, pos) + " é@x.fr   " + line.substring(pos);
                default -> "";
            };
            part.set(at, damaged);
        }
        return String.join("\n", part) + (random.nextBoolean() ? "\n" : "");
    }

    private static boolean writeCase(StringBuilder json, boolean first, String name, String text, String content) {
        if (!first) {
            json.append(",\n");
        }
        json.append("{\"name\": ");
        string(json, name);
        if (text != null) {
            json.append(", \"text\": ");
            string(json, text);
        }
        try {
            VowScanner s = new VowScanner();
            s.start(content, 0, content.length(), 0);
            json.append(",\n \"tokens\": [");
            boolean firstToken = true;
            while (s.kind() != null) {
                json.append(firstToken ? "" : ",").append("[\"").append(s.kind()).append("\",")
                        .append(s.tokenStart()).append(',').append(s.tokenEnd()).append(',').append(s.state()).append(']');
                firstToken = false;
                s.advance();
            }
            json.append("]");
            VowDocument doc = VowDocument.parse(content);
            json.append(",\n \"kind\": ");
            nullable(json, doc.kind());
            json.append(", \"name_in_header\": ");
            nullable(json, doc.name());
            json.append(", \"version\": ");
            nullable(json, doc.version());
            json.append(",\n \"problems\": [");
            boolean firstProblem = true;
            for (VowDocument.Problem p : doc.problems()) {
                json.append(firstProblem ? "" : ",").append('[').append(p.line()).append(',').append(p.start())
                        .append(',').append(p.end()).append(',');
                string(json, p.message());
                json.append(',').append(p.warning()).append(']');
                firstProblem = false;
            }
            json.append("],\n \"links\": [");
            boolean firstLink = true;
            for (VowDocument.Line line : doc.lines()) {
                for (VowLinks.Link link : VowLinks.of(line)) {
                    json.append(firstLink ? "" : ",").append("[\"").append(link.kind()).append("\",");
                    string(json, link.target());
                    json.append(',').append(link.start()).append(',').append(link.end()).append(']');
                    firstLink = false;
                }
            }
            json.append("]");
        } catch (RuntimeException e) {
            json.append(",\n \"exception\": ");
            string(json, e.getClass().getSimpleName());
        }
        json.append("}");
        return false;
    }

    private static void nullable(StringBuilder json, String value) {
        if (value == null) {
            json.append("null");
        } else {
            string(json, value);
        }
    }

    private static void string(StringBuilder json, String value) {
        json.append('"');
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '"' -> json.append("\\\"");
                case '\\' -> json.append("\\\\");
                case '\n' -> json.append("\\n");
                case '\r' -> json.append("\\r");
                case '\t' -> json.append("\\t");
                default -> {
                    if (c < 0x20 || c > 0x7e) {
                        json.append(String.format("\\u%04x", (int) c));
                    } else {
                        json.append(c);
                    }
                }
            }
        }
        json.append('"');
    }
}
