package org.archvow.idea;

import javax.swing.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

public final class VowViewerRegression {
    public static void main(String[] args) throws Exception {
        System.setProperty("java.awt.headless", "true");
        Path root = Files.createTempDirectory("archvow-vow-test");
        Path folder = Files.createDirectories(root.resolve(".archvow/components/config"));
        String source = "vow 1 component config\n# Generated by Archvow\ndecision 1\n  question \"Is this required?\"\n  answer \"Yes\"\n";
        Files.writeString(folder.resolve("spec.vow"), source, StandardCharsets.UTF_8);
        assert source.equals(ArchvowVowViewer.read(root.toString(), "config"));
        assert ArchvowVowViewer.read(root.toString(), "../config").contains("No component spec");
        assert ArchvowVowViewer.read(root.toString(), "unknown").contains("not found");
        SwingUtilities.invokeAndWait(() -> {
            JTextPane pane = ArchvowVowViewer.create();
            ArchvowVowViewer.display(pane, source);
            if (pane.isEditable() || !pane.getText().equals(source)) throw new AssertionError("Invalid vow viewer");
            pane.select(0, 3);
            if (!"vow".equals(pane.getSelectedText())) throw new AssertionError("Text not selectable");
        });
        System.out.println("VowViewerRegression OK");
    }
}
